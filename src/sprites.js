export function drawSprite(ctx, spriteData, x, y, width, height, color) {
  const pixelW = width / 10;
  const pixelH = height / 10;
  ctx.fillStyle = color;
  
  for (let r = 0; r < 10; r++) {
    for (let c = 0; c < 10; c++) {
      if (spriteData[r][c] === 1) {
        ctx.fillRect(x + c * pixelW, y + r * pixelH, pixelW, pixelH);
      }
    }
  }
}
